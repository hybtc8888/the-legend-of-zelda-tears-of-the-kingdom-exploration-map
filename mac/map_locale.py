"""Load the shared catalogs and embed the in-game strings in the Mac build."""
import json
import os
from pathlib import Path

CATALOGS = Path(__file__).resolve().parents[1] / "locales"
GROUPS = json.loads(Path(__file__).with_name("map_groups.json").read_text(encoding="utf-8"))
GROUP_BY_CATEGORY = {cat: group["id"] for group in GROUPS for cat in group["categories"]}
EQUIPMENT_PREFIXES = ("Armor_", "Weapon_")
EQUIPMENT_NAME_SUFFIXES = ("弓", "盾", "剑", "枪", "大剑", "匕首", "长刀", "短刀", "回旋镖", "斧", "锤",
                           "头盔", "面罩", "面具", "铠甲", "护胫", "套装", "杖")

LANGUAGES = ("en", "zh-Hans", "ja", "es", "ru", "fr", "de")


def load_catalogs():
    return {
        code: json.loads((CATALOGS / f"{code}.json").read_text(encoding="utf-8"))
        for code in LANGUAGES
    }


def system_language():
    for name in ("LC_ALL", "LC_MESSAGES", "LANG"):
        if value := os.environ.get(name):
            code = value.replace("_", "-").split("-")[0].split(".")[0].lower()
            return "zh-Hans" if code == "zh" else code if code in LANGUAGES else "en"
    return "en"


def render_header():
    def literal(string):
        return "@" + json.dumps(string, ensure_ascii=False)

    def dictionary(entries):
        return "@{" + ", ".join(f"{literal(key)}: {literal(value)}" for key, value in entries.items()) + "}"

    def strings(values):
        return "@[" + ", ".join(map(literal, values)) + "]"

    catalogs = []
    for code, entry in load_catalogs().items():
        catalogs.append(f'        {literal(code)}: @{{@"name": {literal(entry["name"])},\n'
                        f'            @"ui": {dictionary(entry["ui"])},\n'
                        f'            @"categories": {dictionary(entry["categories"])},\n'
                        f'            @"groups": {dictionary(entry["groups"])}'
                        '}')

    group_ids = [group["id"] for group in GROUPS]
    palette = ", ".join(f"0x{group['color']}" for group in GROUPS)
    category_groups = dictionary(GROUP_BY_CATEGORY)
    return ("/* Generated by mac/integrate.py from the locale catalogs. */\n"
            "static NSArray<NSString *> *mapLanguages(void) {\n"
            f"    return @[{', '.join(map(literal, LANGUAGES))}];\n"
            "}\n\n"
            "static NSDictionary<NSString *, NSDictionary *> *mapCatalogs(void) {\n"
            "    return @{\n" + ",\n".join(catalogs) + "\n    };\n}\n\n"
            f"static NSArray<NSString *> *mapGroupIDs(void) {{ return {strings(group_ids)}; }}\n"
            f"static const unsigned mapGroupColors[] = {{ {palette} }};\n"
            f"static NSDictionary<NSString *, NSString *> *mapCategoryGroups(void) {{ return {category_groups}; }}\n"
            f"static NSArray<NSString *> *mapEquipmentPrefixes(void) {{ return {strings(EQUIPMENT_PREFIXES)}; }}\n"
            f"static NSArray<NSString *> *mapEquipmentSuffixes(void) {{ return {strings(EQUIPMENT_NAME_SUFFIXES)}; }}\n")
