"""Load the shared catalogs and embed the in-game strings in the Mac build."""
import json
import os
from pathlib import Path

CATALOGS = Path(__file__).resolve().parents[1] / "locales"
LANGUAGES = ("en", "zh-Hans", "ja", "es", "ru", "fr", "de")


def load_catalogs():
    return {
        code: json.loads((CATALOGS / f"{code}.json").read_text(encoding="utf-8"))
        for code in LANGUAGES
    }


def system_language():
    for name in ("LC_ALL", "LC_MESSAGES", "LANG"):
        if value := os.environ.get(name):
            code = value.replace("_", "-").split("-")[0].split(".")[0].lower()
            return "zh-Hans" if code == "zh" else code if code in LANGUAGES else "en"
    return "en"


def render_header():
    def literal(string):
        return "@" + json.dumps(string, ensure_ascii=False)

    def dictionary(entries):
        return "@{" + ", ".join(f"{literal(key)}: {literal(value)}" for key, value in entries.items()) + "}"

    catalogs = []
    for code, entry in load_catalogs().items():
        catalogs.append(f'        {literal(code)}: @{{@"name": {literal(entry["name"])},\n'
                        f'            @"ui": {dictionary(entry["ui"])},\n'
                        f'            @"categories": {dictionary(entry["categories"])}'
                        '}')

    return ("/* Generated by mac/integrate.py from the locale catalogs. */\n"
            "static NSArray<NSString *> *mapLanguages(void) {\n"
            f"    return @[{', '.join(map(literal, LANGUAGES))}];\n"
            "}\n\n"
            "static NSDictionary<NSString *, NSDictionary *> *mapCatalogs(void) {\n"
            "    return @{\n" + ",\n".join(catalogs) + "\n    };\n}\n")
